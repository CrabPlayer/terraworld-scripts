// Builds "Open in TerraWorld" links for scripts.
//
// Format (version 1), same as the app's src/lib/scripting/shareLink.ts:
//   https://terraworld.dev/world#script=1.<payload>
//   payload = base64url (no "=" padding) of the zlib stream (deflate + Adler-32) of the
//   script's exact UTF-8 bytes. Opening a link puts the script in the editor; it never runs it.
//
// Usage:
//   node tools/make-link.mjs <file.js> [more files...]   print one link per file
//   node tools/make-link.mjs --update-readme             rewrite the links in samples/README.md
//   node tools/make-link.mjs --check-readme              fail if samples/README.md links are stale (CI)
// Options:
//   --base <url>   page to open (default https://terraworld.dev/world), e.g. http://localhost:5173/world
//
// Every link is decoded again with the app's rules before it is printed, so a link that
// would not open in TerraWorld is never produced.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import zlib from "node:zlib";

export const SCRIPT_LINK_KEY = "script";
export const SCRIPT_LINK_VERSION = "1";
export const SCRIPT_LINK_BASE = "https://terraworld.dev/world";
/** Whole-URL budget for links the app creates (MAX_SCRIPT_LINK_LENGTH in shareLink.ts). */
export const MAX_SCRIPT_LINK_LENGTH = 8192;
/** Limits the app applies when reading a link. */
const MAX_PAYLOAD_CHARS = 64 * 1024;
const MAX_SCRIPT_BYTES = 512 * 1024;

/** Returns `{ ok: true, url }` or `{ ok: false, reason, length, limit }`, like createScriptLink. */
export function createScriptLink(code, base = SCRIPT_LINK_BASE) {
  const payload = zlib.deflateSync(Buffer.from(code, "utf8"), { level: 9 }).toString("base64url");
  const url = `${base.replace(/#.*$/u, "")}#${SCRIPT_LINK_KEY}=${SCRIPT_LINK_VERSION}.${payload}`;
  if (url.length > MAX_SCRIPT_LINK_LENGTH) return { ok: false, reason: "too-long", length: url.length, limit: MAX_SCRIPT_LINK_LENGTH };
  return { ok: true, url };
}

/** Mirrors readScriptFromHash: `{ ok: true, code }`, `{ ok: false, error }`, or null when there is no script link. */
export function readScriptFromUrl(url) {
  const hash = url.includes("#") ? url.slice(url.indexOf("#") + 1) : "";
  if (!hash.startsWith(`${SCRIPT_LINK_KEY}=`)) return null;
  let value = hash.slice(SCRIPT_LINK_KEY.length + 1).trim();
  try { value = decodeURIComponent(value); } catch { /* keep as is */ }
  const dot = value.indexOf(".");
  if (dot < 0) return { ok: false, error: "damaged" };
  const version = value.slice(0, dot);
  const payload = value.slice(dot + 1);
  if (version !== SCRIPT_LINK_VERSION) return { ok: false, error: /^\d+$/u.test(version) ? "unsupported-version" : "damaged" };
  if (payload.length > MAX_PAYLOAD_CHARS) return { ok: false, error: "too-large" };
  if (!/^[A-Za-z0-9_-]+$/u.test(payload)) return { ok: false, error: "damaged" };
  let bytes;
  try {
    bytes = zlib.inflateSync(Buffer.from(payload, "base64url"), { maxOutputLength: MAX_SCRIPT_BYTES });
  } catch (error) {
    return { ok: false, error: error?.code === "ERR_BUFFER_TOO_LARGE" ? "too-large" : "damaged" };
  }
  try {
    return { ok: true, code: new TextDecoder("utf-8", { fatal: true, ignoreBOM: true }).decode(bytes) };
  } catch {
    return { ok: false, error: "damaged" };
  }
}

/** Creates a link and proves it decodes back to the exact same code. Throws otherwise. */
export function makeCheckedLink(code, base = SCRIPT_LINK_BASE, name = "script") {
  const link = createScriptLink(code, base);
  if (!link.ok) throw new Error(`${name}: link would be ${link.length} characters, over the ${link.limit} limit. Share the .js file instead.`);
  const back = readScriptFromUrl(link.url);
  if (!back?.ok) throw new Error(`${name}: link does not decode (${back?.error ?? "no script"})`);
  if (back.code !== code) throw new Error(`${name}: link decodes to different code`);
  return link.url;
}

// ── samples/README.md ────────────────────────────────────────────────

const README = "samples/README.md";
const START = "<!-- links:start -->";
const END = "<!-- links:end -->";

function headerValue(code, key) {
  return new RegExp(`^//\\s*@${key}\\s+(.+)$`, "m").exec(code)?.[1].trim() ?? "";
}

function readmeLinksBlock(base) {
  const files = fs.readdirSync("samples").filter((name) => name.endsWith(".js")).sort();
  const rows = files.map((file) => {
    const code = fs.readFileSync(path.join("samples", file), "utf8");
    const url = makeCheckedLink(code, base, file);
    return `| [${headerValue(code, "name") || file}](${file}) | [Open in TerraWorld](${url}) |`;
  });
  return [
    START,
    "<!-- Generated by `node tools/make-link.mjs --update-readme`. Do not edit by hand. -->",
    "",
    "| Script | Link |",
    "|---|---|",
    ...rows,
    END,
  ].join("\n");
}

function replaceLinksBlock(text, block) {
  const start = text.indexOf(START);
  const end = text.indexOf(END);
  if (start < 0 || end < start) throw new Error(`${README} has no ${START} … ${END} block`);
  return text.slice(0, start) + block + text.slice(end + END.length);
}

// ── CLI ──────────────────────────────────────────────────────────────

function main(argv) {
  let base = SCRIPT_LINK_BASE;
  const files = [];
  let mode = "print";
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--base") base = argv[++i];
    else if (arg === "--update-readme") mode = "update";
    else if (arg === "--check-readme") mode = "check";
    else if (arg === "-h" || arg === "--help") mode = "help";
    else files.push(arg);
  }

  if (mode === "help" || (mode === "print" && !files.length)) {
    console.log("Usage: node tools/make-link.mjs <file.js...> | --update-readme | --check-readme  [--base <url>]");
    return mode === "help" ? 0 : 1;
  }
  if (mode === "print") {
    for (const file of files) console.log(makeCheckedLink(fs.readFileSync(file, "utf8"), base, file));
    return 0;
  }
  const text = fs.readFileSync(README, "utf8");
  const next = replaceLinksBlock(text, readmeLinksBlock(base));
  if (mode === "update") {
    if (next !== text) fs.writeFileSync(README, next);
    console.log(next === text ? `${README} is up to date.` : `Updated links in ${README}.`);
    return 0;
  }
  if (next !== text) {
    console.log(`${README} links do not match the sample code. Run: node tools/make-link.mjs --update-readme`);
    return 1;
  }
  console.log(`${README} links match the samples.`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
